/**
 * NVIDIA judge adapter.
 *
 * Uses shared rate limiter for provider throughput limits.
 */

import type { JudgeAdapter, JudgeInput, JudgeResult } from './types.js';
import { normalizeJudgeConfidence } from './confidence.js';
import { requestNVIDIAChatCompletion } from '../nvidia-polling.js';

export const NVIDIA_JUDGE_GENERATION = {
  temperature: 0,
  max_tokens: 1024,
  reasoning_budget: 256,
} as const;

const JUDGE_SYSTEM_PROMPT = `You are a rigorous evaluation judge. You will be given:
1. A user query
2. An answer generated by an AI system
3. The expected/reference answer
4. The context (retrieved memories) used to generate the answer

Evaluate the answer on four dimensions and return JSON:
{
  "correct": boolean,
  "grounded": boolean,
  "stale": boolean,
  "should_abstain": boolean,
  "confidence": number,
  "reasoning": string
}

Rules:
- "correct" means the answer conveys the same meaning as expected
- "grounded" means the answer can be traced to specific memories in context
- "stale" is true ONLY if the answer contradicts newer information
- "should_abstain" is true if the context doesn't contain enough info
- Return ONLY the JSON object, no markdown fences`;

export function createNVIDIAJudgeAdapter(
  model: string = 'nvidia/nemotron-3-ultra-550b-a55b',
  apiKey?: string,
): JudgeAdapter {
  const key = apiKey || process.env.NVIDIA_API_KEY;
  if (!key) throw new Error('NVIDIA_API_KEY required for NVIDIA judge adapter');

  return {
    name: `nvidia:${model}`,

    async judge(input: JudgeInput): Promise<JudgeResult> {
      const started = Date.now();

      const contextBlock = input.context.length > 0
        ? input.context.map((c, i) => `[${i + 1}] ${c}`).join('\n\n')
        : 'No context provided.';

      const userPrompt = `Query: ${input.query}

Context:
${contextBlock}

Expected: ${input.expected}

Generated: ${input.answer}

Evaluate. Return JSON only.`;

      const data = await requestNVIDIAChatCompletion({
        apiKey: key,
        label: 'judge',
        body: {
          model,
          messages: [
            { role: 'system', content: JUDGE_SYSTEM_PROMPT },
            { role: 'user', content: userPrompt },
          ],
          ...NVIDIA_JUDGE_GENERATION,
          stream: false,
        },
      });
      const content = data.choices[0].message.content.trim();
      const latencyMs = Date.now() - started;

      try {
        const parsed: unknown = JSON.parse(content);
        if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) throw new Error('Judge output must be a JSON object');
        const verdict = parsed as Record<string, unknown>;
        return {
          correct: Boolean(verdict.correct),
          grounded: Boolean(verdict.grounded),
          stale: Boolean(verdict.stale),
          shouldAbstain: Boolean(verdict.should_abstain),
          confidence: normalizeJudgeConfidence(verdict.confidence),
          reasoning: String(verdict.reasoning || ''),
          latencyMs,
          tokens: {
            prompt: data.usage?.prompt_tokens ?? 0,
            completion: data.usage?.completion_tokens ?? 0,
          },
        };
      } catch {
        return {
          correct: false,
          grounded: false,
          stale: false,
          shouldAbstain: false,
          confidence: 0,
          reasoning: `Failed to parse judge output: ${content}`,
          latencyMs,
        };
      }
    },
  };
}
